#!/usr/bin/env node
/**
 * Derive `.dev.vars` (what `wrangler dev` loads locally) from `.env.local`.
 *
 * Cloudflare Workers do not read `.env.local`; `wrangler dev` reads `.dev.vars`,
 * and a deployed Worker reads secrets set with `wrangler secret put`. Both are
 * gitignored. This script exists so the local half is one documented command
 * instead of a hand-copied file — and so the Vercel-only variables never ride
 * along into a Cloudflare runtime that has no use for them.
 *
 * It never prints a value, only the names it wrote.
 *
 * Usage:
 *   node scripts/cloudflare-dev-vars.mjs            # write .dev.vars
 *   node scripts/cloudflare-dev-vars.mjs --dry-run  # list names only
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '.env.local');
const target = join(root, '.dev.vars');
const dryRun = process.argv.includes('--dry-run');

/**
 * Variables that only ever meant anything to Vercel. Carrying them into a
 * Worker would suggest a dependency that no longer exists.
 */
const NOT_FOR_CLOUDFLARE = [/^VERCEL_/];

if (!existsSync(source)) {
  console.error('No .env.local found — nothing to derive .dev.vars from.');
  process.exit(1);
}

const kept = [];
const skipped = [];

for (const rawLine of readFileSync(source, 'utf8').split(/\r?\n/)) {
  const line = rawLine.trim();
  if (!line || line.startsWith('#')) continue;
  const eq = line.indexOf('=');
  if (eq === -1) continue;

  const name = line.slice(0, eq).trim();
  if (NOT_FOR_CLOUDFLARE.some((pattern) => pattern.test(name))) {
    skipped.push(name);
    continue;
  }

  // `wrangler dev` parses .dev.vars line by line, so a value containing a
  // newline or quote has to be quoted and escaped to survive the round trip.
  const value = line.slice(eq + 1).trim();
  const needsQuotes = /[\s"'#]/.test(value);
  const body = needsQuotes
    ? `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
    : value;
  kept.push(`${name}=${body}`);
}

if (dryRun) {
  console.log('Would write to .dev.vars:');
  for (const line of kept) console.log(`  ${line.slice(0, line.indexOf('='))}`);
  if (skipped.length) console.log(`Skipped (Vercel-only): ${skipped.join(', ')}`);
  process.exit(0);
}

writeFileSync(
  target,
  [
    '# Generated by scripts/cloudflare-dev-vars.mjs from .env.local.',
    '# Local-only Worker secrets — never commit this file.',
    ...kept,
    '',
  ].join('\n'),
);

console.log(`Wrote .dev.vars with ${kept.length} variable(s):`);
for (const line of kept) console.log(`  ${line.slice(0, line.indexOf('='))}`);
if (skipped.length) console.log(`Skipped Vercel-only: ${skipped.join(', ')}`);
